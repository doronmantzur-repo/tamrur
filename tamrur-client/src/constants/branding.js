/**
 * The application's name, as shown to users.
 *
 * Written with a Hebrew gershayim (U+05F4, ״) rather than an ASCII double
 * quote: it marks תמרו״ר as an acronym, and unlike `"` it is a Hebrew letter-
 * class character, so it never gets reordered by the bidi algorithm when the
 * name sits next to Latin text or punctuation.
 *
 * The name is deliberately not derived from any identifier — the repo folders,
 * the axios client and the storage keys all keep their `tamrur` spelling.
 */
